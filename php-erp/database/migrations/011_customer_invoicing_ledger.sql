CREATE TABLE IF NOT EXISTS accounting_journals (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    code VARCHAR(16) NOT NULL,
    name VARCHAR(120) NOT NULL,
    journal_type VARCHAR(20) NOT NULL DEFAULT 'sale',
    active TINYINT(1) NOT NULL DEFAULT 1,
    created_by BIGINT UNSIGNED NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_accounting_journal_company_code (company_id, code),
    KEY idx_accounting_journal_company_type (company_id, journal_type, active),
    CONSTRAINT fk_accounting_journal_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_accounting_journal_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_accounting_journal_type CHECK (journal_type IN ('sale','purchase','bank','cash','general'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS customer_invoice_sequences (
    company_id BIGINT UNSIGNED NOT NULL,
    sequence_year SMALLINT UNSIGNED NOT NULL,
    last_number BIGINT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (company_id, sequence_year),
    CONSTRAINT fk_customer_invoice_sequence_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS accounting_moves (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    name VARCHAR(40) NOT NULL,
    journal_id BIGINT UNSIGNED NOT NULL,
    move_type VARCHAR(32) NOT NULL,
    reference_model VARCHAR(40) NOT NULL,
    reference_id BIGINT UNSIGNED NOT NULL,
    reference VARCHAR(120) NOT NULL,
    accounting_date DATE NOT NULL,
    currency_code CHAR(3) NOT NULL,
    state VARCHAR(16) NOT NULL DEFAULT 'draft',
    total_debit DECIMAL(20,6) NOT NULL DEFAULT 0,
    total_credit DECIMAL(20,6) NOT NULL DEFAULT 0,
    created_by BIGINT UNSIGNED NOT NULL,
    posted_by BIGINT UNSIGNED NULL,
    posted_at DATETIME NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_accounting_move_company_name (company_id, name),
    UNIQUE KEY uq_accounting_move_source (reference_model, reference_id),
    KEY idx_accounting_move_company_date (company_id, accounting_date, state, id),
    CONSTRAINT fk_accounting_move_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_accounting_move_journal FOREIGN KEY (journal_id) REFERENCES accounting_journals (id) ON DELETE RESTRICT,
    CONSTRAINT fk_accounting_move_currency FOREIGN KEY (currency_code) REFERENCES currencies (currency_code) ON DELETE RESTRICT,
    CONSTRAINT fk_accounting_move_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_accounting_move_poster FOREIGN KEY (posted_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_accounting_move_state CHECK (state IN ('draft','posted','reversed')),
    CONSTRAINT chk_accounting_move_totals CHECK (total_debit >= 0 AND total_credit >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

