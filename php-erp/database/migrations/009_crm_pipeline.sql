CREATE TABLE IF NOT EXISTS crm_stages (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    name VARCHAR(120) NOT NULL,
    sequence SMALLINT UNSIGNED NOT NULL DEFAULT 10,
    probability DECIMAL(5,2) NOT NULL DEFAULT 0,
    is_won TINYINT(1) NOT NULL DEFAULT 0,
    active TINYINT(1) NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_crm_stage_company_name (company_id, name),
    KEY idx_crm_stage_pipeline (company_id, active, sequence, id),
    CONSTRAINT fk_crm_stage_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT chk_crm_stage_probability CHECK (probability >= 0 AND probability <= 100)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS crm_teams (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    name VARCHAR(120) NOT NULL,
    leader_user_id BIGINT UNSIGNED NULL,
    email_alias VARCHAR(190) NULL,
    active TINYINT(1) NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_crm_team_company_name (company_id, name),
    KEY idx_crm_team_company_active (company_id, active, name),
    CONSTRAINT fk_crm_team_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_crm_team_leader FOREIGN KEY (leader_user_id) REFERENCES users (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS crm_leads (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    partner_contact_id BIGINT UNSIGNED NULL,
    name VARCHAR(190) NOT NULL,
    contact_type VARCHAR(24) NOT NULL DEFAULT 'person',
    email VARCHAR(190) NULL,
    phone VARCHAR(80) NULL,
    mobile VARCHAR(80) NULL,
    website VARCHAR(255) NULL,
    record_type VARCHAR(24) NOT NULL DEFAULT 'lead',
    stage_id BIGINT UNSIGNED NOT NULL,
    team_id BIGINT UNSIGNED NULL,
    salesperson_user_id BIGINT UNSIGNED NULL,
    expected_revenue DECIMAL(20,6) NOT NULL DEFAULT 0,
    currency_code CHAR(3) NOT NULL DEFAULT 'BDT',
    probability DECIMAL(5,2) NOT NULL DEFAULT 0,
    priority TINYINT UNSIGNED NOT NULL DEFAULT 0,
    expected_close_date DATE NULL,
    source VARCHAR(120) NULL,
    medium VARCHAR(120) NULL,
    campaign VARCHAR(190) NULL,
    description TEXT NULL,
    state VARCHAR(24) NOT NULL DEFAULT 'open',
    lost_reason VARCHAR(500) NULL,
    converted_at DATETIME NULL,
    created_by BIGINT UNSIGNED NOT NULL,
    updated_by BIGINT UNSIGNED NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_crm_lead_company_pipeline (company_id, state, record_type, stage_id, priority, id),
    KEY idx_crm_lead_partner (partner_contact_id),
    KEY idx_crm_lead_owner (company_id, salesperson_user_id, state),
    KEY idx_crm_lead_team (company_id, team_id, state),
    KEY idx_crm_lead_updated (company_id, updated_at),
    CONSTRAINT fk_crm_lead_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_crm_lead_partner FOREIGN KEY (partner_contact_id) REFERENCES contacts (id) ON DELETE RESTRICT,
    CONSTRAINT fk_crm_lead_stage FOREIGN KEY (stage_id) REFERENCES crm_stages (id) ON DELETE RESTRICT,
    CONSTRAINT fk_crm_lead_team FOREIGN KEY (team_id) REFERENCES crm_teams (id) ON DELETE RESTRICT,
    CONSTRAINT fk_crm_lead_salesperson FOREIGN KEY (salesperson_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_crm_lead_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_crm_lead_updater FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_crm_lead_record_type CHECK (record_type IN ('lead', 'opportunity')),
    CONSTRAINT chk_crm_lead_contact_type CHECK (contact_type IN ('person', 'company')),
    CONSTRAINT chk_crm_lead_state CHECK (state IN ('open', 'won', 'lost')),
    CONSTRAINT chk_crm_lead_priority CHECK (priority BETWEEN 0 AND 3),
    CONSTRAINT chk_crm_lead_probability CHECK (probability >= 0 AND probability <= 100),
    CONSTRAINT chk_crm_lead_revenue CHECK (expected_revenue >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS crm_activities (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    lead_id BIGINT UNSIGNED NOT NULL,
    activity_type VARCHAR(24) NOT NULL DEFAULT 'todo',
    summary VARCHAR(190) NOT NULL,
    due_at DATETIME NULL,
    assigned_user_id BIGINT UNSIGNED NULL,
    state VARCHAR(24) NOT NULL DEFAULT 'planned',
    completed_at DATETIME NULL,
    created_by BIGINT UNSIGNED NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_crm_activity_lead (company_id, lead_id, state, due_at, id),
    KEY idx_crm_activity_user (company_id, assigned_user_id, state, due_at),
    CONSTRAINT fk_crm_activity_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_crm_activity_lead FOREIGN KEY (lead_id) REFERENCES crm_leads (id) ON DELETE RESTRICT,
    CONSTRAINT fk_crm_activity_assignee FOREIGN KEY (assigned_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_crm_activity_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_crm_activity_type CHECK (activity_type IN ('todo', 'call', 'meeting', 'email', 'upload', 'other')),
    CONSTRAINT chk_crm_activity_state CHECK (state IN ('planned', 'done', 'cancelled'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
