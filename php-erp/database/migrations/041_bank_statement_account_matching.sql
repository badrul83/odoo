CREATE TABLE IF NOT EXISTS bank_statement_account_matches (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    journal_id BIGINT UNSIGNED NOT NULL,
    statement_line_id BIGINT UNSIGNED NOT NULL,
    account_id BIGINT UNSIGNED NOT NULL,
    reference VARCHAR(190) NOT NULL,
    transaction_date DATE NOT NULL,
    amount DECIMAL(20,6) NOT NULL,
    currency_code CHAR(3) NOT NULL,
    accounting_move_id BIGINT UNSIGNED NULL,
    created_by BIGINT UNSIGNED NOT NULL,
    matched_at DATETIME NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_bank_statement_account_match_line (statement_line_id),
    UNIQUE KEY uq_bank_statement_account_match_move (accounting_move_id),
    KEY idx_bank_statement_account_match_company_date (company_id, journal_id, transaction_date, id),
    CONSTRAINT fk_bank_statement_account_match_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_bank_statement_account_match_journal FOREIGN KEY (journal_id) REFERENCES accounting_journals (id) ON DELETE RESTRICT,
    CONSTRAINT fk_bank_statement_account_match_line FOREIGN KEY (statement_line_id) REFERENCES bank_statement_lines (id) ON DELETE RESTRICT,
    CONSTRAINT fk_bank_statement_account_match_account FOREIGN KEY (account_id) REFERENCES accounting_accounts (id) ON DELETE RESTRICT,
    CONSTRAINT fk_bank_statement_account_match_currency FOREIGN KEY (currency_code) REFERENCES currencies (currency_code) ON DELETE RESTRICT,
    CONSTRAINT fk_bank_statement_account_match_move FOREIGN KEY (accounting_move_id) REFERENCES accounting_moves (id) ON DELETE RESTRICT,
    CONSTRAINT fk_bank_statement_account_match_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_bank_statement_account_match_amount CHECK (amount > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
