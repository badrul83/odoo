    PRIMARY KEY (id),
    UNIQUE KEY uq_mrp_order_company_reference (company_id, reference),
    KEY idx_mrp_order_company_state (company_id, state, scheduled_at, id),
    KEY idx_mrp_order_product (company_id, product_id, created_at),
