CREATE TABLE IF NOT EXISTS customer_credit_note_refund_sequences (
    company_id BIGINT UNSIGNED NOT NULL,
    sequence_year SMALLINT UNSIGNED NOT NULL,
    last_number BIGINT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (company_id, sequence_year),
    CONSTRAINT fk_customer_credit_note_refund_sequence_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS customer_credit_note_refunds (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    name VARCHAR(40) NOT NULL,
    credit_note_id BIGINT UNSIGNED NOT NULL,
    partner_contact_id BIGINT UNSIGNED NOT NULL,
    journal_id BIGINT UNSIGNED NOT NULL,
    currency_code CHAR(3) NOT NULL,
    payment_date DATE NOT NULL,
    amount DECIMAL(20,6) NOT NULL,
    reference VARCHAR(190) NULL,
    state VARCHAR(16) NOT NULL DEFAULT 'in_payment',
    accounting_move_id BIGINT UNSIGNED NULL,
    created_by BIGINT UNSIGNED NOT NULL,
    paid_at DATETIME NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_customer_credit_note_refund_company_name (company_id, name),
    UNIQUE KEY uq_customer_credit_note_refund_move (accounting_move_id),
    KEY idx_customer_credit_note_refund_note (company_id, credit_note_id, state, id),
    CONSTRAINT fk_customer_credit_note_refund_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_customer_credit_note_refund_note FOREIGN KEY (credit_note_id) REFERENCES customer_invoices (id) ON DELETE RESTRICT,
    CONSTRAINT fk_customer_credit_note_refund_partner FOREIGN KEY (partner_contact_id) REFERENCES contacts (id) ON DELETE RESTRICT,
    CONSTRAINT fk_customer_credit_note_refund_journal FOREIGN KEY (journal_id) REFERENCES accounting_journals (id) ON DELETE RESTRICT,
    CONSTRAINT fk_customer_credit_note_refund_currency FOREIGN KEY (currency_code) REFERENCES currencies (currency_code) ON DELETE RESTRICT,
    CONSTRAINT fk_customer_credit_note_refund_move FOREIGN KEY (accounting_move_id) REFERENCES accounting_moves (id) ON DELETE RESTRICT,
    CONSTRAINT fk_customer_credit_note_refund_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_customer_credit_note_refund_state CHECK (state IN ('in_payment','paid','cancelled')),
    CONSTRAINT chk_customer_credit_note_refund_amount CHECK (amount > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS customer_credit_note_refund_allocations (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    credit_note_id BIGINT UNSIGNED NOT NULL,
    refund_id BIGINT UNSIGNED NOT NULL,
    credit_note_receivable_line_id BIGINT UNSIGNED NOT NULL,
    refund_receivable_line_id BIGINT UNSIGNED NOT NULL,
    amount DECIMAL(20,6) NOT NULL,
    created_by BIGINT UNSIGNED NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_credit_note_refund_allocation_refund (refund_id),
    KEY idx_credit_note_refund_allocation_note (company_id, credit_note_id, id),
    CONSTRAINT fk_credit_note_refund_allocation_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_credit_note_refund_allocation_note FOREIGN KEY (credit_note_id) REFERENCES customer_invoices (id) ON DELETE RESTRICT,
    CONSTRAINT fk_credit_note_refund_allocation_refund FOREIGN KEY (refund_id) REFERENCES customer_credit_note_refunds (id) ON DELETE RESTRICT,
    CONSTRAINT fk_credit_note_refund_allocation_note_line FOREIGN KEY (credit_note_receivable_line_id) REFERENCES accounting_move_lines (id) ON DELETE RESTRICT,
    CONSTRAINT fk_credit_note_refund_allocation_refund_line FOREIGN KEY (refund_receivable_line_id) REFERENCES accounting_move_lines (id) ON DELETE RESTRICT,
    CONSTRAINT fk_credit_note_refund_allocation_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_credit_note_refund_allocation_amount CHECK (amount > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS customer_credit_note_refund_matches (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    journal_id BIGINT UNSIGNED NOT NULL,
    refund_id BIGINT UNSIGNED NOT NULL,
    statement_line_id BIGINT UNSIGNED NULL,
    reference VARCHAR(190) NOT NULL,
    transaction_date DATE NOT NULL,
    amount DECIMAL(20,6) NOT NULL,
    currency_code CHAR(3) NOT NULL,
    accounting_move_id BIGINT UNSIGNED NULL,
    created_by BIGINT UNSIGNED NOT NULL,
    matched_at DATETIME NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_credit_note_refund_match_refund (refund_id),
    UNIQUE KEY uq_credit_note_refund_match_statement_line (statement_line_id),
    UNIQUE KEY uq_credit_note_refund_match_move (accounting_move_id),
    KEY idx_credit_note_refund_match_company_date (company_id, journal_id, transaction_date, id),
    CONSTRAINT fk_credit_note_refund_match_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_credit_note_refund_match_journal FOREIGN KEY (journal_id) REFERENCES accounting_journals (id) ON DELETE RESTRICT,
    CONSTRAINT fk_credit_note_refund_match_refund FOREIGN KEY (refund_id) REFERENCES customer_credit_note_refunds (id) ON DELETE RESTRICT,
    CONSTRAINT fk_credit_note_refund_match_line FOREIGN KEY (statement_line_id) REFERENCES bank_statement_lines (id) ON DELETE RESTRICT,
    CONSTRAINT fk_credit_note_refund_match_currency FOREIGN KEY (currency_code) REFERENCES currencies (currency_code) ON DELETE RESTRICT,
    CONSTRAINT fk_credit_note_refund_match_move FOREIGN KEY (accounting_move_id) REFERENCES accounting_moves (id) ON DELETE RESTRICT,
    CONSTRAINT fk_credit_note_refund_match_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_credit_note_refund_match_amount CHECK (amount > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
