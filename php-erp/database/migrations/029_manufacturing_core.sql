CREATE TABLE IF NOT EXISTS manufacturing_work_centers (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(120) NOT NULL,
    capacity DECIMAL(12,4) NOT NULL DEFAULT 1,
    time_efficiency DECIMAL(8,4) NOT NULL DEFAULT 100,
    cost_per_hour DECIMAL(20,6) NOT NULL DEFAULT 0,
    active TINYINT(1) NOT NULL DEFAULT 1,
    created_by BIGINT UNSIGNED NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_mrp_work_center_company_code (company_id, code),
    KEY idx_mrp_work_center_company_active (company_id, active, name),
    CONSTRAINT fk_mrp_work_center_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_mrp_work_center_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS manufacturing_boms (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    product_id BIGINT UNSIGNED NOT NULL,
    code VARCHAR(80) NULL,
    product_quantity DECIMAL(20,6) NOT NULL DEFAULT 1,
    uom_id BIGINT UNSIGNED NOT NULL,
    bom_type VARCHAR(20) NOT NULL DEFAULT 'manufacture',
    active TINYINT(1) NOT NULL DEFAULT 1,
    created_by BIGINT UNSIGNED NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_mrp_bom_company_code (company_id, code),
    KEY idx_mrp_bom_product_active (company_id, product_id, active, id),
    CONSTRAINT fk_mrp_bom_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_mrp_bom_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT,
    CONSTRAINT fk_mrp_bom_uom FOREIGN KEY (uom_id) REFERENCES units_of_measure (id) ON DELETE RESTRICT,
    CONSTRAINT fk_mrp_bom_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

