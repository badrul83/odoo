CREATE TABLE IF NOT EXISTS appointment_resources (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    name VARCHAR(120) NOT NULL,
    capacity SMALLINT UNSIGNED NOT NULL DEFAULT 1,
    timezone VARCHAR(80) NOT NULL DEFAULT 'Asia/Dhaka',
    description VARCHAR(1000) NOT NULL DEFAULT '',
    active TINYINT(1) NOT NULL DEFAULT 1,
    created_by BIGINT UNSIGNED NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_appointment_resource_id_company (id, company_id),
    UNIQUE KEY uq_appointment_resource_name_company (company_id, name),
    KEY idx_appointment_resource_company (company_id, active, name),
    CONSTRAINT fk_appointment_resource_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointment_resource_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_appointment_resource_capacity CHECK (capacity BETWEEN 1 AND 500)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS appointment_types (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    name VARCHAR(120) NOT NULL,
    public_token CHAR(64) NOT NULL,
    duration_minutes SMALLINT UNSIGNED NOT NULL DEFAULT 30,
    slot_interval_minutes SMALLINT UNSIGNED NOT NULL DEFAULT 30,
    prebooking_minutes INT UNSIGNED NOT NULL DEFAULT 60,
    booking_horizon_days SMALLINT UNSIGNED NOT NULL DEFAULT 60,
    date_start DATE NULL,
    date_end DATE NULL,
    cancellation_cutoff_minutes INT UNSIGNED NOT NULL DEFAULT 0,
    assignment_target VARCHAR(16) NOT NULL DEFAULT 'user',
    assignment_method VARCHAR(16) NOT NULL DEFAULT 'automatic',
    location_type VARCHAR(16) NOT NULL DEFAULT 'online',
    location VARCHAR(255) NOT NULL DEFAULT '',
    capacity_per_slot SMALLINT UNSIGNED NOT NULL DEFAULT 1,
    allow_guests TINYINT(1) NOT NULL DEFAULT 0,
    timezone VARCHAR(80) NOT NULL DEFAULT 'Asia/Dhaka',
    intro_message VARCHAR(2000) NOT NULL DEFAULT '',
    confirmation_message VARCHAR(2000) NOT NULL DEFAULT '',
    published TINYINT(1) NOT NULL DEFAULT 0,
    active TINYINT(1) NOT NULL DEFAULT 1,
    created_by BIGINT UNSIGNED NOT NULL,
    updated_by BIGINT UNSIGNED NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_appointment_type_id_company (id, company_id),
    UNIQUE KEY uq_appointment_type_token (public_token),
    UNIQUE KEY uq_appointment_type_name_company (company_id, name),
    KEY idx_appointment_type_company (company_id, active, published, name),
    CONSTRAINT fk_appointment_type_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointment_type_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointment_type_updater FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_appointment_duration CHECK (duration_minutes BETWEEN 5 AND 1440),
    CONSTRAINT chk_appointment_slot_interval CHECK (slot_interval_minutes BETWEEN 5 AND 1440),
    CONSTRAINT chk_appointment_capacity CHECK (capacity_per_slot BETWEEN 1 AND 500),
    CONSTRAINT chk_appointment_assignment_target CHECK (assignment_target IN ('user','resource')),
    CONSTRAINT chk_appointment_assignment_method CHECK (assignment_method IN ('automatic','visitor')),
    CONSTRAINT chk_appointment_location_type CHECK (location_type IN ('online','physical','phone')),
    CONSTRAINT chk_appointment_date_window CHECK (date_start IS NULL OR date_end IS NULL OR date_start <= date_end)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS appointment_type_users (
    company_id BIGINT UNSIGNED NOT NULL,
    appointment_type_id BIGINT UNSIGNED NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    PRIMARY KEY (appointment_type_id, user_id),
    KEY idx_appointment_type_user_company (company_id, user_id, appointment_type_id),
    CONSTRAINT fk_appointment_type_user_type FOREIGN KEY (appointment_type_id, company_id) REFERENCES appointment_types (id, company_id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointment_type_user_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS appointment_type_resources (
    company_id BIGINT UNSIGNED NOT NULL,
    appointment_type_id BIGINT UNSIGNED NOT NULL,
    resource_id BIGINT UNSIGNED NOT NULL,
    PRIMARY KEY (appointment_type_id, resource_id),
    KEY idx_appointment_type_resource_company (company_id, resource_id, appointment_type_id),
    CONSTRAINT fk_appointment_type_resource_type FOREIGN KEY (appointment_type_id, company_id) REFERENCES appointment_types (id, company_id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointment_type_resource_resource FOREIGN KEY (resource_id, company_id) REFERENCES appointment_resources (id, company_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS appointment_availabilities (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    appointment_type_id BIGINT UNSIGNED NOT NULL,
    weekday TINYINT UNSIGNED NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_appointment_availability_id_company (id, company_id),
    KEY idx_appointment_availability_type_day (appointment_type_id, company_id, weekday, start_time),
    CONSTRAINT fk_appointment_availability_type FOREIGN KEY (appointment_type_id, company_id) REFERENCES appointment_types (id, company_id) ON DELETE RESTRICT,
    CONSTRAINT chk_appointment_availability_weekday CHECK (weekday BETWEEN 0 AND 6),
    CONSTRAINT chk_appointment_availability_time CHECK (start_time < end_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS appointment_questions (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    appointment_type_id BIGINT UNSIGNED NOT NULL,
    question VARCHAR(255) NOT NULL,
    answer_type VARCHAR(16) NOT NULL DEFAULT 'text',
    is_required TINYINT(1) NOT NULL DEFAULT 0,
    sequence SMALLINT UNSIGNED NOT NULL DEFAULT 10,
    active TINYINT(1) NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_appointment_question_id_company (id, company_id),
    KEY idx_appointment_question_type (appointment_type_id, company_id, active, sequence),
    CONSTRAINT fk_appointment_question_type FOREIGN KEY (appointment_type_id, company_id) REFERENCES appointment_types (id, company_id) ON DELETE RESTRICT,
    CONSTRAINT chk_appointment_question_answer_type CHECK (answer_type IN ('text','email','phone','number'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS appointment_bookings (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    appointment_type_id BIGINT UNSIGNED NOT NULL,
    contact_id BIGINT UNSIGNED NULL,
    assigned_user_id BIGINT UNSIGNED NULL,
    resource_id BIGINT UNSIGNED NULL,
    booking_name VARCHAR(190) NOT NULL,
    email VARCHAR(190) NOT NULL DEFAULT '',
    phone VARCHAR(80) NOT NULL DEFAULT '',
    starts_at_utc DATETIME NOT NULL,
    ends_at_utc DATETIME NOT NULL,
    timezone VARCHAR(80) NOT NULL,
    guest_count SMALLINT UNSIGNED NOT NULL DEFAULT 1,
    status VARCHAR(16) NOT NULL DEFAULT 'booked',
    source VARCHAR(16) NOT NULL DEFAULT 'internal',
    notes VARCHAR(2000) NOT NULL DEFAULT '',
    cancellation_reason VARCHAR(500) NOT NULL DEFAULT '',
    booking_token CHAR(64) NOT NULL,
    created_by BIGINT UNSIGNED NULL,
    cancelled_by BIGINT UNSIGNED NULL,
    cancelled_at DATETIME NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_appointment_booking_id_company (id, company_id),
    UNIQUE KEY uq_appointment_booking_token (booking_token),
    KEY idx_appointment_booking_company_start (company_id, starts_at_utc, status, id),
    KEY idx_appointment_booking_contact (company_id, contact_id, starts_at_utc),
    KEY idx_appointment_booking_user_time (company_id, assigned_user_id, starts_at_utc, ends_at_utc, status),
    KEY idx_appointment_booking_resource_time (company_id, resource_id, starts_at_utc, ends_at_utc, status),
    CONSTRAINT fk_appointment_booking_type FOREIGN KEY (appointment_type_id, company_id) REFERENCES appointment_types (id, company_id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointment_booking_contact FOREIGN KEY (contact_id) REFERENCES contacts (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointment_booking_user FOREIGN KEY (assigned_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointment_booking_resource FOREIGN KEY (resource_id, company_id) REFERENCES appointment_resources (id, company_id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointment_booking_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointment_booking_canceller FOREIGN KEY (cancelled_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_appointment_booking_provider CHECK ((assigned_user_id IS NOT NULL AND resource_id IS NULL) OR (assigned_user_id IS NULL AND resource_id IS NOT NULL)),
    CONSTRAINT chk_appointment_booking_status CHECK (status IN ('booked','cancelled','completed','no_show')),
    CONSTRAINT chk_appointment_booking_source CHECK (source IN ('internal','public')),
    CONSTRAINT chk_appointment_booking_time CHECK (starts_at_utc < ends_at_utc),
    CONSTRAINT chk_appointment_booking_guest_count CHECK (guest_count BETWEEN 1 AND 500)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS appointment_answers (
    company_id BIGINT UNSIGNED NOT NULL,
    booking_id BIGINT UNSIGNED NOT NULL,
    question_id BIGINT UNSIGNED NOT NULL,
    answer_text VARCHAR(2000) NOT NULL DEFAULT '',
    PRIMARY KEY (booking_id, question_id),
    KEY idx_appointment_answer_company_question (company_id, question_id),
    CONSTRAINT fk_appointment_answer_booking FOREIGN KEY (booking_id, company_id) REFERENCES appointment_bookings (id, company_id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointment_answer_question FOREIGN KEY (question_id, company_id) REFERENCES appointment_questions (id, company_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
