    CONSTRAINT fk_mrp_order_bom FOREIGN KEY (bom_id) REFERENCES manufacturing_boms (id) ON DELETE RESTRICT,
    CONSTRAINT fk_mrp_order_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT,
    CONSTRAINT fk_mrp_order_uom FOREIGN KEY (uom_id) REFERENCES units_of_measure (id) ON DELETE RESTRICT,
