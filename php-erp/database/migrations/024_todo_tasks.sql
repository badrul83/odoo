CREATE TABLE IF NOT EXISTS todo_stages (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    stage_key VARCHAR(40) NOT NULL,
    name VARCHAR(50) NOT NULL,
    sequence SMALLINT UNSIGNED NOT NULL,
    rotting_days SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    folded_by_default TINYINT(1) NOT NULL DEFAULT 0,
    stage_type VARCHAR(16) NOT NULL DEFAULT 'open',
    is_required TINYINT(1) NOT NULL DEFAULT 0,
    active TINYINT(1) NOT NULL DEFAULT 1,
    created_by BIGINT UNSIGNED NULL,
    updated_by BIGINT UNSIGNED NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_todo_stage_company_key (company_id, stage_key),
    UNIQUE KEY uq_todo_stage_id_company (id, company_id),
    KEY idx_todo_stage_company_sequence (company_id, active, sequence, id),
    CONSTRAINT fk_todo_stage_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_todo_stage_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_todo_stage_updater FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_todo_stage_type CHECK (stage_type IN ('open','done','cancelled'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS todo_tasks (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    title VARCHAR(120) NOT NULL,
    description VARCHAR(2000) NOT NULL DEFAULT '',
    stage_id BIGINT UNSIGNED NOT NULL,
    stage_entered_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    priority TINYINT UNSIGNED NOT NULL DEFAULT 0,
    tag VARCHAR(40) NOT NULL DEFAULT '',
    deadline DATE NULL,
    reminder TINYINT(1) NOT NULL DEFAULT 0,
    contact_id BIGINT UNSIGNED NULL,
    source_model VARCHAR(40) NULL,
    source_record_id BIGINT UNSIGNED NULL,
    source_reference VARCHAR(190) NULL,
    created_by BIGINT UNSIGNED NOT NULL,
    updated_by BIGINT UNSIGNED NOT NULL,
    completed_at DATETIME NULL,
    archived_at DATETIME NULL,
    archived_by BIGINT UNSIGNED NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_todo_task_id_company (id, company_id),
    KEY idx_todo_task_company_stage (company_id, stage_id, archived_at, deadline, id),
    KEY idx_todo_task_contact (company_id, contact_id, archived_at, id),
    KEY idx_todo_task_source (company_id, source_model, source_record_id),
    KEY idx_todo_task_creator (created_by, company_id, archived_at),
    CONSTRAINT fk_todo_task_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_todo_task_stage_company FOREIGN KEY (stage_id, company_id) REFERENCES todo_stages (id, company_id) ON DELETE RESTRICT,
    CONSTRAINT fk_todo_task_contact FOREIGN KEY (contact_id) REFERENCES contacts (id) ON DELETE RESTRICT,
    CONSTRAINT fk_todo_task_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_todo_task_updater FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_todo_task_archiver FOREIGN KEY (archived_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_todo_task_priority CHECK (priority BETWEEN 0 AND 3),
    CONSTRAINT chk_todo_task_source_pair CHECK ((source_model IS NULL AND source_record_id IS NULL) OR (source_model IS NOT NULL AND source_record_id IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS todo_task_assignees (
    company_id BIGINT UNSIGNED NOT NULL,
    task_id BIGINT UNSIGNED NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    assigned_by BIGINT UNSIGNED NOT NULL,
    assigned_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (task_id, user_id),
    KEY idx_todo_assignee_company_user (company_id, user_id, task_id),
    CONSTRAINT fk_todo_assignee_task_company FOREIGN KEY (task_id, company_id) REFERENCES todo_tasks (id, company_id) ON DELETE RESTRICT,
    CONSTRAINT fk_todo_assignee_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_todo_assignee_actor FOREIGN KEY (assigned_by) REFERENCES users (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
