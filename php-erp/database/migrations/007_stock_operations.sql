CREATE TABLE IF NOT EXISTS stock_lots (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    product_id BIGINT UNSIGNED NOT NULL,
    lot_code VARCHAR(120) NOT NULL,
    expiration_date DATE NULL,
    active TINYINT(1) NOT NULL DEFAULT 1,
    created_by BIGINT UNSIGNED NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_stock_lot_company_product_code (company_id, product_id, lot_code),
    KEY idx_stock_lot_product (product_id, active, expiration_date),
    CONSTRAINT fk_stock_lot_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_stock_lot_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT,
    CONSTRAINT fk_stock_lot_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS stock_moves (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    reference VARCHAR(40) NULL,
    product_id BIGINT UNSIGNED NOT NULL,
    uom_id BIGINT UNSIGNED NOT NULL,
    source_location_id BIGINT UNSIGNED NOT NULL,
    destination_location_id BIGINT UNSIGNED NOT NULL,
    demand_quantity DECIMAL(20, 6) NOT NULL,
    done_quantity DECIMAL(20, 6) NOT NULL DEFAULT 0,
    state VARCHAR(16) NOT NULL DEFAULT 'draft',
    origin_model VARCHAR(40) NULL,
    origin_record_id BIGINT UNSIGNED NULL,
    origin_reference VARCHAR(120) NULL,
    scheduled_at DATETIME NULL,
    done_at DATETIME NULL,
    created_by BIGINT UNSIGNED NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_stock_move_company_reference (company_id, reference),
    KEY idx_stock_move_company_state (company_id, state, scheduled_at, id),
    KEY idx_stock_move_product (product_id, state, created_at),
    KEY idx_stock_move_source (source_location_id, state),
    KEY idx_stock_move_destination (destination_location_id, state),
    KEY idx_stock_move_origin (origin_model, origin_record_id),
    CONSTRAINT fk_stock_move_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_stock_move_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT,
    CONSTRAINT fk_stock_move_uom FOREIGN KEY (uom_id) REFERENCES units_of_measure (id) ON DELETE RESTRICT,
    CONSTRAINT fk_stock_move_source FOREIGN KEY (source_location_id) REFERENCES stock_locations (id) ON DELETE RESTRICT,
    CONSTRAINT fk_stock_move_destination FOREIGN KEY (destination_location_id) REFERENCES stock_locations (id) ON DELETE RESTRICT,
    CONSTRAINT fk_stock_move_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS stock_move_lines (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    move_id BIGINT UNSIGNED NOT NULL,
    lot_id BIGINT UNSIGNED NULL,
    lot_code_snapshot VARCHAR(120) NULL,
    expiration_date_snapshot DATE NULL,
    quantity DECIMAL(20, 6) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_stock_move_line_lot_code (move_id, lot_code_snapshot),
    KEY idx_stock_move_line_lot (lot_id, move_id),
    CONSTRAINT fk_stock_move_line_move FOREIGN KEY (move_id) REFERENCES stock_moves (id) ON DELETE RESTRICT,
    CONSTRAINT fk_stock_move_line_lot FOREIGN KEY (lot_id) REFERENCES stock_lots (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS stock_quants (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    product_id BIGINT UNSIGNED NOT NULL,
    location_id BIGINT UNSIGNED NOT NULL,
    lot_id BIGINT UNSIGNED NULL,
    lot_key VARCHAR(24) NOT NULL DEFAULT 'NONE',
    quantity DECIMAL(20, 6) NOT NULL DEFAULT 0,
    reserved_quantity DECIMAL(20, 6) NOT NULL DEFAULT 0,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_stock_quant_dimensions (company_id, product_id, location_id, lot_key),
    KEY idx_stock_quant_product_location (company_id, product_id, location_id),
    KEY idx_stock_quant_lot (lot_id),
    CONSTRAINT fk_stock_quant_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_stock_quant_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT,
    CONSTRAINT fk_stock_quant_location FOREIGN KEY (location_id) REFERENCES stock_locations (id) ON DELETE RESTRICT,
    CONSTRAINT fk_stock_quant_lot FOREIGN KEY (lot_id) REFERENCES stock_lots (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
