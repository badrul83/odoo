    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    move_id BIGINT UNSIGNED NOT NULL,
    sequence SMALLINT UNSIGNED NOT NULL DEFAULT 10,
    account_id BIGINT UNSIGNED NOT NULL,
    contact_id BIGINT UNSIGNED NULL,
    label VARCHAR(190) NOT NULL,
    debit DECIMAL(20,6) NOT NULL DEFAULT 0,
    credit DECIMAL(20,6) NOT NULL DEFAULT 0,
    currency_code CHAR(3) NOT NULL,
    amount_currency DECIMAL(20,6) NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_accounting_move_line_move (move_id, sequence, id),
    KEY idx_accounting_move_line_account (account_id, move_id),
    KEY idx_accounting_move_line_contact (contact_id, account_id, move_id),
    CONSTRAINT fk_accounting_move_line_move FOREIGN KEY (move_id) REFERENCES accounting_moves (id) ON DELETE RESTRICT,
    CONSTRAINT fk_accounting_move_line_account FOREIGN KEY (account_id) REFERENCES accounting_accounts (id) ON DELETE RESTRICT,
    CONSTRAINT fk_accounting_move_line_contact FOREIGN KEY (contact_id) REFERENCES contacts (id) ON DELETE RESTRICT,
    CONSTRAINT fk_accounting_move_line_currency FOREIGN KEY (currency_code) REFERENCES currencies (currency_code) ON DELETE RESTRICT,
    CONSTRAINT chk_accounting_move_line_amounts CHECK (debit >= 0 AND credit >= 0 AND NOT (debit > 0 AND credit > 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

