CREATE TABLE IF NOT EXISTS sales_taxes (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NULL,
    name VARCHAR(120) NOT NULL,
    amount DECIMAL(9,4) NOT NULL DEFAULT 0,
    price_included TINYINT(1) NOT NULL DEFAULT 0,
    active TINYINT(1) NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_sales_tax_company_name (company_id, name),
    KEY idx_sales_tax_company_active (company_id, active, name),
    CONSTRAINT fk_sales_tax_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT chk_sales_tax_amount CHECK (amount >= 0 AND amount <= 100)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS sales_order_sequences (
    company_id BIGINT UNSIGNED NOT NULL,
    sequence_year SMALLINT UNSIGNED NOT NULL,
    last_number BIGINT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (company_id, sequence_year),
    CONSTRAINT fk_sales_sequence_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS sales_orders (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    name VARCHAR(40) NOT NULL,
    partner_contact_id BIGINT UNSIGNED NOT NULL,
    invoice_contact_id BIGINT UNSIGNED NULL,
    delivery_contact_id BIGINT UNSIGNED NULL,
    crm_lead_id BIGINT UNSIGNED NULL,
    salesperson_user_id BIGINT UNSIGNED NULL,
    pricelist_id BIGINT UNSIGNED NULL,
    payment_terms_id BIGINT UNSIGNED NULL,
    warehouse_id BIGINT UNSIGNED NULL,
    currency_code CHAR(3) NOT NULL,
    order_date DATE NOT NULL,
    validity_date DATE NULL,
    state VARCHAR(16) NOT NULL DEFAULT 'draft',
    client_order_ref VARCHAR(190) NULL,
    note TEXT NULL,
    untaxed_amount DECIMAL(20,6) NOT NULL DEFAULT 0,
    tax_amount DECIMAL(20,6) NOT NULL DEFAULT 0,
    total_amount DECIMAL(20,6) NOT NULL DEFAULT 0,
    sent_at DATETIME NULL,
    confirmed_at DATETIME NULL,
    cancelled_at DATETIME NULL,
    created_by BIGINT UNSIGNED NOT NULL,
    updated_by BIGINT UNSIGNED NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_sales_order_company_name (company_id, name),
    KEY idx_sales_order_company_state_date (company_id, state, order_date, id),
    KEY idx_sales_order_customer (company_id, partner_contact_id, state),
    KEY idx_sales_order_crm (crm_lead_id, state),
    KEY idx_sales_order_salesperson (company_id, salesperson_user_id, state),
    CONSTRAINT fk_sales_order_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sales_order_customer FOREIGN KEY (partner_contact_id) REFERENCES contacts (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sales_order_invoice_contact FOREIGN KEY (invoice_contact_id) REFERENCES contacts (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sales_order_delivery_contact FOREIGN KEY (delivery_contact_id) REFERENCES contacts (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sales_order_crm FOREIGN KEY (crm_lead_id) REFERENCES crm_leads (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sales_order_salesperson FOREIGN KEY (salesperson_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sales_order_pricelist FOREIGN KEY (pricelist_id) REFERENCES price_lists (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sales_order_payment_terms FOREIGN KEY (payment_terms_id) REFERENCES payment_terms (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sales_order_warehouse FOREIGN KEY (warehouse_id) REFERENCES warehouses (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sales_order_currency FOREIGN KEY (currency_code) REFERENCES currencies (currency_code) ON DELETE RESTRICT,
    CONSTRAINT fk_sales_order_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sales_order_updater FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_sales_order_state CHECK (state IN ('draft','sent','sale','cancelled')),
    CONSTRAINT chk_sales_order_amounts CHECK (untaxed_amount >= 0 AND tax_amount >= 0 AND total_amount >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS sales_order_lines (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    order_id BIGINT UNSIGNED NOT NULL,
    sequence SMALLINT UNSIGNED NOT NULL DEFAULT 10,
    product_id BIGINT UNSIGNED NOT NULL,
    uom_id BIGINT UNSIGNED NOT NULL,
    description VARCHAR(500) NOT NULL,
    quantity DECIMAL(20,6) NOT NULL,
    unit_price DECIMAL(20,6) NOT NULL DEFAULT 0,
    discount_percent DECIMAL(7,4) NOT NULL DEFAULT 0,
    tax_id BIGINT UNSIGNED NULL,
    tax_name_snapshot VARCHAR(120) NULL,
    tax_rate_snapshot DECIMAL(9,4) NOT NULL DEFAULT 0,
    tax_included_snapshot TINYINT(1) NOT NULL DEFAULT 0,
    subtotal DECIMAL(20,6) NOT NULL DEFAULT 0,
    tax_amount DECIMAL(20,6) NOT NULL DEFAULT 0,
    total DECIMAL(20,6) NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_sales_order_line_order (order_id, sequence, id),
    KEY idx_sales_order_line_product (product_id, order_id),
    CONSTRAINT fk_sales_order_line_order FOREIGN KEY (order_id) REFERENCES sales_orders (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sales_order_line_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sales_order_line_uom FOREIGN KEY (uom_id) REFERENCES units_of_measure (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sales_order_line_tax FOREIGN KEY (tax_id) REFERENCES sales_taxes (id) ON DELETE RESTRICT,
    CONSTRAINT chk_sales_order_line_quantity CHECK (quantity > 0),
    CONSTRAINT chk_sales_order_line_discount CHECK (discount_percent >= 0 AND discount_percent <= 100),
    CONSTRAINT chk_sales_order_line_amounts CHECK (unit_price >= 0 AND subtotal >= 0 AND tax_amount >= 0 AND total >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
