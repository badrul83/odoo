    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    invoice_id BIGINT UNSIGNED NOT NULL,
    sequence SMALLINT UNSIGNED NOT NULL DEFAULT 10,
    sales_order_line_id BIGINT UNSIGNED NOT NULL,
    product_id BIGINT UNSIGNED NOT NULL,
    uom_id BIGINT UNSIGNED NOT NULL,
    description VARCHAR(500) NOT NULL,
    quantity DECIMAL(20,6) NOT NULL,
    unit_price DECIMAL(20,6) NOT NULL DEFAULT 0,
    discount_percent DECIMAL(7,4) NOT NULL DEFAULT 0,
    tax_id BIGINT UNSIGNED NULL,
    tax_name_snapshot VARCHAR(120) NULL,
    tax_rate_snapshot DECIMAL(9,4) NOT NULL DEFAULT 0,
    tax_included_snapshot TINYINT(1) NOT NULL DEFAULT 0,
    subtotal DECIMAL(20,6) NOT NULL DEFAULT 0,
    tax_amount DECIMAL(20,6) NOT NULL DEFAULT 0,
    total DECIMAL(20,6) NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_customer_invoice_line_invoice (invoice_id, sequence, id),
    CONSTRAINT fk_customer_invoice_line_invoice FOREIGN KEY (invoice_id) REFERENCES customer_invoices (id) ON DELETE RESTRICT,
    CONSTRAINT fk_customer_invoice_line_sales_line FOREIGN KEY (sales_order_line_id) REFERENCES sales_order_lines (id) ON DELETE RESTRICT,
    CONSTRAINT fk_customer_invoice_line_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT,
    CONSTRAINT fk_customer_invoice_line_uom FOREIGN KEY (uom_id) REFERENCES units_of_measure (id) ON DELETE RESTRICT,
    CONSTRAINT fk_customer_invoice_line_tax FOREIGN KEY (tax_id) REFERENCES sales_taxes (id) ON DELETE RESTRICT,
    CONSTRAINT chk_customer_invoice_line_quantity CHECK (quantity > 0),
    CONSTRAINT chk_customer_invoice_line_amounts CHECK (subtotal >= 0 AND tax_amount >= 0 AND total >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
