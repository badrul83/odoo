CREATE TABLE IF NOT EXISTS inventory_valuation_closings (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    company_id BIGINT UNSIGNED NOT NULL,
    name VARCHAR(40) NOT NULL,
    as_of_date DATE NOT NULL,
    currency_code CHAR(3) NOT NULL,
    state VARCHAR(16) NOT NULL DEFAULT 'draft',
    physical_value DECIMAL(20,6) NOT NULL DEFAULT 0,
    accounting_value DECIMAL(20,6) NOT NULL DEFAULT 0,
    difference_value DECIMAL(20,6) NOT NULL DEFAULT 0,
    journal_id BIGINT UNSIGNED NOT NULL,
    accounting_move_id BIGINT UNSIGNED NULL,
    created_by BIGINT UNSIGNED NOT NULL,
    updated_by BIGINT UNSIGNED NOT NULL,
    posted_by BIGINT UNSIGNED NULL,
    posted_at DATETIME NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_inventory_closing_company_name (company_id, name),
    UNIQUE KEY uq_inventory_closing_accounting_move (accounting_move_id),
    KEY idx_inventory_closing_company_date (company_id, as_of_date, state, id),
    CONSTRAINT fk_inventory_closing_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_closing_currency FOREIGN KEY (currency_code) REFERENCES currencies (currency_code) ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_closing_journal FOREIGN KEY (journal_id) REFERENCES accounting_journals (id) ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_closing_move FOREIGN KEY (accounting_move_id) REFERENCES accounting_moves (id) ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_closing_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_closing_updater FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_closing_poster FOREIGN KEY (posted_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_inventory_closing_state CHECK (state IN ('draft','posted','discarded'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS inventory_valuation_closing_lines (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    closing_id BIGINT UNSIGNED NOT NULL,
    sequence SMALLINT UNSIGNED NOT NULL,
    valuation_account_id BIGINT UNSIGNED NOT NULL,
    variation_account_id BIGINT UNSIGNED NOT NULL,
    physical_value DECIMAL(20,6) NOT NULL DEFAULT 0,
    accounting_value DECIMAL(20,6) NOT NULL DEFAULT 0,
    difference_value DECIMAL(20,6) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uq_inventory_closing_line_account (closing_id, valuation_account_id),
    CONSTRAINT fk_inventory_closing_line_closing FOREIGN KEY (closing_id) REFERENCES inventory_valuation_closings (id) ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_closing_line_valuation_account FOREIGN KEY (valuation_account_id) REFERENCES accounting_accounts (id) ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_closing_line_variation_account FOREIGN KEY (variation_account_id) REFERENCES accounting_accounts (id) ON DELETE RESTRICT,
    CONSTRAINT chk_inventory_closing_line_distinct_accounts CHECK (valuation_account_id <> variation_account_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
